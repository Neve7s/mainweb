lines.push('async function callNvidia(env, messages) {');
lines.push('  const apiKey = env.NVIDIA_API_KEY;');
lines.push('  if (!apiKey) return { ok: false, status: 500, error: "Missing NVIDIA_API_KEY secret" };');
lines.push('  const models = (env.NVIDIA_MODELS || "").split(",").map((m) => m.trim()).filter(Boolean);');
lines.push('  const modelList = models.length ? models : [env.NVIDIA_MODEL || "nvidia/nemotron-mini-4b-instruct"];');
lines.push('  for (const model of modelList) {');
