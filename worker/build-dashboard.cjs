lines.push('    const sanitized = [];');
lines.push('    for (const m of messages) { if (typeof m !== "object" || m === null) continue; const role = m.role === "assistant" ? "assistant" : "user"; const content = typeof m.content === "string" ? m.content.trim().slice(0, 600) : ""; if (!content) continue; sanitized.push({ role, content }); }');
lines.push('    if (sanitized.length === 0) return json({ error: "No valid messages" }, 400, cors);');
lines.push('    const systemPrompt = buildKnowledge(lang);');
lines.push('    const result = await callNvidia(env, [{ role: "system", content: systemPrompt }, ...sanitized]);');
lines.push('    if (!result.ok) return json({ error: result.error }, result.status, cors);');
lines.push('    return json({ reply: result.reply }, 200, cors);');
lines.push('  },');
