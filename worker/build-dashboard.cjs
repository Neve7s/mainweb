lines.push('    const cors = { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Methods": "POST, OPTIONS", "Access-Control-Allow-Headers": "Content-Type", "Cache-Control": "no-store" };');
lines.push('    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });');
lines.push('    if (request.method === "GET" && url.pathname === "/health") return json({ ok: true }, 200, cors);');
lines.push('    if (request.method !== "POST") return json({ error: "Method not allowed" }, 405, cors);');
lines.push('    const ip = request.headers.get("cf-connecting-ip") || "unknown";');
lines.push('    if (rateLimited(ip)) return json({ error: "Too many requests. Please wait a minute." }, 429, cors);');
lines.push('    let body; try { body = await request.json(); } catch { return json({ error: "Invalid JSON body" }, 400, cors); }');
lines.push('    const lang = body.lang === "en" ? "en" : "es";');
lines.push('    const messages = Array.isArray(body.messages) ? body.messages : [];');
